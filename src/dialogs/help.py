"""Окно «Инструкция пользователя» (открывается по F1)."""
import customtkinter as ctk
from tkinter import scrolledtext

from theme import COL_BG_DARK, COL_TEXT_LIGHT

from .base import BaseDialog, CANCEL

HELP_TEXT = """\
ОБЗОР
Программа предназначена для просмотра и анализа записей ЭКГ (вариабельность
сердечного ритма, ВСР) спортсменов. Записи снимаются нагрудным пульсометром
Polar H10 и хранятся в базе данных. Окно разделено на список спортсменов слева
и тепловые карты / графики справа.

СПИСОК СПОРТСМЕНОВ (левая колонка)
- ＋ — добавить спортсмена, ✎ — редактировать, 🗑 — удалить.
- 📋 Список ЭКГ — журнал записей атлета.
- ⬇ Импорт записи ЭКГ — загрузить одну или несколько записей.
Выбор спортсмена обновляет тепловые карты и графики.

КАРТОЧКА СПОРТСМЕНА (окно добавления/редактирования)
Фамилия и имя обязательны. Пол, дата рождения, рост/вес и Polar ID —
по желанию. Кнопка «Сформировать шаблон» создаёт биометрический шаблон по
имеющимся записям спортсмена (нужно минимум 8 записей) — используется для
автоматического распознавания атлета и процента схожести.

ИМПОРТ ЗАПИСЕЙ ЭКГ
Выберите один или несколько файлов .teamloggerh10. Импорт выполняет
биометрическую проверку: если запись не совпадает с текущим атлетом и найден
более подходящий шаблон — программа предложит исправить привязку. Дубликаты
по времени импорта пропускаются.

НАВИГАЦИЯ ПО ВРЕМЕНИ
- Год / неделя переключаются в правом окне.
- Тепловая карта: блок (3 часа) дня кликается для просмотра ЭКГ за этот
  интервал. Оранжевые столбики — индекс стресса, зелёные — TP.
- Клик по году на heatmap выделяет неделю и открывает недельные графики.

ГРАФИКИ TP И ИНДЕКСА СТРЕССА
- Клик, колесо мыши, панорамирование мышью — масштабирование и перемещение.
- ПКМ (правый клик) — сброс масштаба к диапазону данных.

ЖУРНАЛ ЭКГ
- Колонка «Сходство» — % биологической схожести записи с шаблоном атлета.
  Низкая схожесть подсвечивается (жёлтый < порога, красный < критического).
- Сортировка — кликом по заголовку колонки или кнопками «По времени снятия /
  По времени импорта».
- «🎯 Улучшить сходство» — показывает всех атлетов по убыванию сходства и
  переназначает запись нужному спортсмену.
- «🗑 Удалить» — удалить выбранную запись, «Экспорт в файл» — сохранить raw-данные.

БИОМЕТРИЯ / ОПРЕДЕЛЕНИЕ АТЛЕТА
- Для каждого спортсмена из его записей формируется шаблон (форма сигнала и
  спектр). При импорте/проверке запись сравнивается с шаблонами всех атлетов —
  наибольшее совпадение указывает на владельца записи.
- Процент сходства сохраняется в БД; у записей, загруженных до создания
  шаблона, он автоматически дозаполняется после его формирования.

ГОРЯЧИЕ КЛАВИШИ
- F1 — эта инструкция.
"""


class HelpDialog(BaseDialog):
    """Немодальное окно справки с прокручиваемым текстом."""

    def __init__(self, parent):
        super().__init__(parent, title="Инструкция пользователя",
                         size="640x520", resizable=(True, True), modal=False)

        ctk.CTkLabel(self, text="Инструкция пользователя",
                     font=ctk.CTkFont(size=15, weight="bold")).pack(pady=(12, 4))

        txt = scrolledtext.ScrolledText(
            self, wrap="word", padx=12, pady=12,
            font=("Segoe UI", 10),
            bg=COL_BG_DARK, fg=COL_TEXT_LIGHT, insertbackground=COL_TEXT_LIGHT)
        txt.insert("1.0", HELP_TEXT)
        txt.configure(state="disabled")
        txt.pack(fill="both", expand=True, padx=10, pady=(0, 6))

        self.make_button(self, "Закрыть", self.close, kind=CANCEL, side="top", pady=10,
                         tooltip="Закрыть инструкцию")

        self._center_over_parent()